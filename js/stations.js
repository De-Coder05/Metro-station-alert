// Helper: flat list of all stations with city/line metadata attached
function getAllStations() {
  const result = [];
  for (const [cityKey, city] of Object.entries(METRO_SYSTEMS)) {
    for (const [lineName, line] of Object.entries(city.lines)) {
      for (const stn of line.stations) {
        result.push({
          ...stn,
          cityKey,
          cityName: city.name,
          lineName,
          lineColor: line.color,
        });
      }
    }
  }
  return result;
}
